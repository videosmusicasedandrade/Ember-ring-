export function getArenaForStage(stageNumber: number): ArenaConfig {
  const stage = Math.max(1, Math.floor(stageNumber));
  const presetIndex = (stage - 1) % MAP_PRESETS.length;
  const preset = MAP_PRESETS[presetIndex];

  const slots: ArenaSlot[] = preset.slots.map((s) => ({
    id: s.id,
    x: s.x,
    y: s.y,
    ring: s.zone,
    angle: s.angle,
    radius: 28,
    unitId: null,
  }));

  return {
    worldWidth: 1200,
    worldHeight: 820,
    centerX: 580,
    centerY: 410,
    castleX: preset.castleX,
    castleY: preset.castleY,
    castleRadius: preset.castleRadius,
    roadHalfWidth: preset.roadHalfWidth,
    waypoints: preset.waypoints,
    mapId: preset.id,
    stageTitle: `${preset.name} (Fase ${stage})`,
    theme: preset.theme,
    themeColors: {
      bgGradient: [preset.colors.bgInner, preset.colors.bgMid, preset.colors.bgOuter],
      terraceColor: preset.colors.terrace,
      roadShadow: preset.colors.roadShadow,
      roadBorder: preset.colors.roadBorder,
      roadCurb: preset.colors.roadCurb,
      roadSurface: preset.colors.roadSurface,
      roadInner: preset.colors.roadInner,
      roadSpeckle: preset.colors.roadSpeckle,
      bushColor: preset.colors.foliageDark,
      bushHighlight: preset.colors.foliageLight,
      bushOutline: preset.colors.foliageOutline,
      treeColor1: preset.colors.foliageDark,
      treeColor2: preset.colors.foliageLight,
      treeTrunk: preset.colors.trunk,
      pondWater: [preset.colors.waterShallow, preset.colors.waterDeep],
      pondBank: preset.colors.waterRim,
      pondOutline: preset.colors.roadBorder,
    },
    slots,
  };
}
